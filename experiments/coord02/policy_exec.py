"""coordination-procedure/1 execution transport over broker sandbox-exec.

Mirrors the representation-01 durable-step pattern (DEC-EC02-01): every
policy step and every probe call is a real broker operation with a real
receipt, so a fresh process resumes settled effects from the database
instead of rerunning them. Generated bytes are never imported.
"""

from __future__ import annotations

import json
from typing import Any

from psycopg.rows import dict_row

from settlement import broker, db
from settlement.common import ResultCode, SettlementError
from settlement.representation import canonical_bytes, sha_hex

from .schemas import (
    MAX_MESSAGE_BYTES,
    PROFILE,
    PolicyError,
    parse_response_bytes,
    request_bytes,
)

ENTRY_FILENAME = "policy.py"
REQUEST_FILENAME = "request.json"
RESPONSE_FILENAME = "response.json"
STEP_RECEIPT_KIND = "coord-step"
PROBE_RECEIPT_KIND = "coord-probe"


def step_op_id(run_id: str, task_id: str, seq: int) -> str:
    for value, name in ((run_id, "run_id"), (task_id, "task_id")):
        if not isinstance(value, str) or not value or len(value) > 64:
            raise SettlementError(f"illegal {name} {value!r}")
    if seq < 0:
        raise SettlementError(f"illegal step identity {seq}")
    return f"coord:{run_id}:{task_id}:step:{seq:04d}"


def probe_op_id(run_id: str, task_id: str, seq: int, idx: int) -> str:
    return f"{step_op_id(run_id, task_id, seq)}:probe:{idx}"


def _receipts(dsn: str, operation_id: str) -> list[dict]:
    with db.connect(dsn) as conn:
        with conn.cursor(row_factory=dict_row) as cur:
            cur.execute("SELECT receipt_identity, outcome, content FROM receipts"
                        " WHERE operation_id = %s ORDER BY created_at",
                        (operation_id,))
            rows = [dict(r) for r in cur.fetchall()]
            conn.commit()
            return rows


def _find(receipts: list[dict], identity: str) -> dict | None:
    return next((r for r in receipts
                 if r.get("receipt_identity") == identity), None)


def _sandbox_timed_out(receipts: list[dict]) -> bool:
    cands = [r for r in receipts
             if (r.get("receipt_identity") or "").startswith("local:")]
    if not cands:
        return False
    try:
        return bool((cands[-1].get("content") or {}).get("data", {})
                    .get("timed_out", False))
    except AttributeError:
        return False


def _admit(dsn: str, operation_id: str, identity: str, content: dict) -> None:
    broker.admit_launcher_receipt(
        dsn, operation_id,
        broker.ReceiptProposal(receipt_identity=identity, content=content,
                               outcome="unknown", provenance=PROFILE))


def invoke_policy_step(dsn: str, launcher: Any, *, run_id: str, task_id: str,
                       seq: int, entry_bytes: bytes, request: dict,
                       allocation_id: str, attempt_id: str | None = None,
                       timeout_ms: int = 2000) -> dict:
    op_id = step_op_id(run_id, task_id, seq)
    identity = f"{STEP_RECEIPT_KIND}:{op_id}"
    recorded = _find(_receipts(dsn, op_id), identity)
    if recorded is not None:
        content = dict(recorded.get("content") or {})
        if content.get("protocol_refusal"):
            raise PolicyError(content["protocol_refusal"]["reason"],
                              content["protocol_refusal"].get("detail", ""))
        if content.get("transport") in ("timeout", "empty"):
            raise PolicyError(content["transport"],
                              f"recorded step {op_id} never produced a reply")
        return {"op_id": op_id, "reused": True,
                "proposal": content["proposal"], "action": content["action"],
                "state": content.get("state"),
                "decision_id": content.get("decision_id")}
    try:
        raw_request = request_bytes(request)
    except PolicyError as exc:
        _admit(dsn, op_id, identity,
               {"kind": STEP_RECEIPT_KIND, "op_id": op_id,
                "protocol_refusal": {"reason": exc.reason, "detail": exc.detail}})
        raise
    in_dir, out_dir = launcher.exec_dirs(op_id, PROFILE)
    ensured = broker.ensure_operation(
        dsn, operation_id=op_id, effect=broker.SANDBOX_EXEC,
        payload={"profile": launcher.profile,
                 "argv": [launcher.staged_python(), f"{in_dir}/{ENTRY_FILENAME}",
                          f"{in_dir}/{REQUEST_FILENAME}",
                          f"{out_dir}/{RESPONSE_FILENAME}"],
                 "timeout_ms": timeout_ms,
                 "max_output_bytes": MAX_MESSAGE_BYTES},
        allocation_id=allocation_id, attempt_id=attempt_id,
        execution_version=PROFILE)
    if ensured.code not in (ResultCode.APPLIED, ResultCode.ALREADY_APPLIED):
        if ensured.code != ResultCode.INVALID_INPUT or \
                broker.read_operation(dsn, op_id) is None:
            raise SettlementError(
                f"policy invocation {op_id} not admitted: {ensured.detail}")
    launcher.stage_input(op_id, PROFILE, ENTRY_FILENAME, entry_bytes)
    launcher.stage_input(op_id, PROFILE, REQUEST_FILENAME, raw_request)
    broker.dispatch_operation(dsn, op_id,
                              launchers={launcher.profile: launcher})
    receipts = _receipts(dsn, op_id)
    timed_out = _sandbox_timed_out(receipts)
    try:
        raw_response = launcher.read_output(op_id, PROFILE, RESPONSE_FILENAME)
    except OSError:
        raw_response = None
    if timed_out or not raw_response:
        kind = "timeout" if timed_out else "empty"
        _admit(dsn, op_id, identity,
               {"kind": STEP_RECEIPT_KIND, "op_id": op_id,
                "decision_id": request.get("decision_id"),
                "request_digest": sha_hex(raw_request),
                "request": json.loads(raw_request.decode("utf-8")),
                "transport": kind, "timed_out": timed_out})
        raise PolicyError(kind, f"policy step {op_id} produced no reply")
    try:
        parsed = parse_response_bytes(
            raw_response, decision_id=request["decision_id"],
            package_digest=request["package_digest"],
            source_digest=request["source_digest"],
            plan_revision=request["plan_revision"], phase=request["phase"],
            allowed=request["allowed_actions"])
    except PolicyError as exc:
        _admit(dsn, op_id, identity,
               {"kind": STEP_RECEIPT_KIND, "op_id": op_id,
                "decision_id": request.get("decision_id"),
                "request_digest": sha_hex(raw_request),
                "request": json.loads(raw_request.decode("utf-8")),
                "protocol_refusal": {"reason": exc.reason,
                                     "detail": exc.detail}})
        raise
    _admit(dsn, op_id, identity,
           {"kind": STEP_RECEIPT_KIND, "op_id": op_id,
            "decision_id": request.get("decision_id"),
            "request_digest": sha_hex(raw_request),
            "request": json.loads(raw_request.decode("utf-8")),
            "action": parsed["action"], "proposal": parsed["proposal"],
            "state": parsed["state"], "timed_out": False})
    return {"op_id": op_id, "reused": False, "proposal": parsed["proposal"],
            "action": parsed["action"], "state": parsed["state"],
            "decision_id": request.get("decision_id")}


def run_probe_call(dsn: str, launcher: Any, *, run_id: str, task_id: str,
                   seq: int, idx: int, interface: str, interface_bytes: bytes,
                   call_input: dict, allocation_id: str,
                   attempt_id: str | None = None,
                   timeout_ms: int = 5000) -> dict:
    op_id = probe_op_id(run_id, task_id, seq, idx)
    identity = f"{PROBE_RECEIPT_KIND}:{op_id}"
    recorded = _find(_receipts(dsn, op_id), identity)
    if recorded is not None:
        content = dict(recorded.get("content") or {})
        return {"op_id": op_id, "reused": True,
                "observation": content["observation"]}
    raw_input = canonical_bytes({"interface": interface, "input": call_input})
    in_dir, out_dir = launcher.exec_dirs(op_id, PROFILE)
    ensured = broker.ensure_operation(
        dsn, operation_id=op_id, effect=broker.SANDBOX_EXEC,
        payload={"profile": launcher.profile,
                 "argv": [launcher.staged_python(), f"{in_dir}/iface.py",
                          f"{in_dir}/input.json", f"{out_dir}/output.json"],
                 "timeout_ms": timeout_ms,
                 "max_output_bytes": MAX_MESSAGE_BYTES},
        allocation_id=allocation_id, attempt_id=attempt_id,
        execution_version=PROFILE)
    if ensured.code not in (ResultCode.APPLIED, ResultCode.ALREADY_APPLIED):
        raise SettlementError(
            f"probe invocation {op_id} not admitted: {ensured.detail}")
    launcher.stage_input(op_id, PROFILE, "iface.py", interface_bytes)
    launcher.stage_input(op_id, PROFILE, "input.json", raw_input)
    broker.dispatch_operation(dsn, op_id,
                              launchers={launcher.profile: launcher})
    receipts = _receipts(dsn, op_id)
    timed_out = _sandbox_timed_out(receipts)
    try:
        raw_output = launcher.read_output(op_id, PROFILE, "output.json")
        output_text = raw_output.decode("utf-8")
    except (OSError, UnicodeDecodeError):
        output_text = ""
    try:
        parsed_output = json.loads(output_text) if output_text else None
    except ValueError:
        parsed_output = None
    observation = {"interface": interface, "input": call_input,
                   "output": parsed_output, "raw_truncated": output_text[:4096],
                   "timed_out": timed_out,
                   "error": None if parsed_output is not None and not timed_out
                   else "probe produced no JSON observation"}
    _admit(dsn, op_id, identity,
           {"kind": PROBE_RECEIPT_KIND, "op_id": op_id,
            "interface": interface,
            "input_digest": sha_hex(raw_input),
            "observation": observation})
    return {"op_id": op_id, "reused": False, "observation": observation}
