def probe_continuity_phase1(dsn: str, *, gateway, launchers: dict,
                            runs_root: Path, tag: str,
                            task_id: str) -> dict:
    """Solve + submit one S episode, then stop before assembly.

    Writes a state file; a separate process must complete the episode.
    """
    started = time.monotonic()
    epid = "live2-S-%s-r1-continuity" % task_id
    nonce = uuid.uuid4().hex[:8]
    area = runs_root / epid
    area.mkdir(parents=True, exist_ok=True)
    _panel.register.ensure_foundation(dsn)
    seed = _panel._seed(dsn, "%s-%s" % (tag, epid))
    snapshot = _panel._snapshot(task_id)
    ctx = SolverCtx(dsn, gateway, launchers, runs_root,
                    seed["allocation_id"], "%s-%s-%s" % (tag, epid, nonce),
                    task_id, snapshot, area)
    prefix = "%s-%s-%s" % (tag, epid, nonce)
    owned = sorted(p for p in snapshot if p.startswith("src/"))
    solved = solve_S(ctx, owned=owned, prefix=prefix)
    if not solved["w1"]:
        return {"episode_id": epid, "outcome": "refused",
                "reason": "phase-1 solve produced no bytes"}
    children = _live_children("single", snapshot)
    proposed = team.propose_team_plan(
        dsn, _cmd(), parent_obligation="%s:repair %s" % (
            seed["investigation_id"], task_id),
        snapshot_digest=team.register_snapshot(
            dsn, _cmd(), dict(snapshot)).data["snapshot_digest"],
        shape="single", children=children,
        interface_contract={"shapes": ["single"], "new_paths": []},
        join_rules=_panel._join_rules("single", task_id),
        allocation_id=seed["allocation_id"],
        policy_response={"arm": "S", "shape": "single",
                         "continuity": "phase-1"})
    if proposed.code != ResultCode.APPLIED:
        return {"episode_id": epid, "outcome": "refused",
                "reason": "phase-1 plan refused: %s" % proposed.detail}
    plan_id = proposed.data["plan_id"]
    receipts = _panel._dispatch(dsn, plan_id, launchers)
    digests = _submit_nodes(dsn, plan_id, 1, {"w1": solved["w1"]},
                            receipts)
    state = {"episode_id": epid, "task_id": task_id, "plan_id": plan_id,
             "nonce": nonce, "tag": tag,
             "allocation_id": seed["allocation_id"],
             "submitted_digests": digests,
             "snapshot": snapshot,
             "constructor_ops": [t for t in ctx.trace
                                 if t.get("kind") in ("ctor", "plan",
                                                      "review")],
             "tool_ops": [t for t in ctx.trace
                          if t.get("kind") == "tool"],
             "model_calls": ctx.model_calls, "tool_calls": ctx.tool_calls,
             "wall_s": round(time.monotonic() - started, 3)}
    (area / "continuity-state.json").write_text(json.dumps(state))
    return {"episode_id": epid, "outcome": "suspended", "plan_id": plan_id,
            "state_file": str(area / "continuity-state.json")}


