ROOT = Path(__file__).resolve().parent

MODEL = "muse-spark-1.3-contributor-free"
EFFORT = "low"
MAX_OUTPUT_TOKENS = 8192
DEADLINE_MS = 300_000
RETRIES = 0

MAX_CTOR_ROUNDS_S = 3
MAX_TOOL_CALLS_S = 4
MAX_TOOL_CALLS_NODE = 2
SELF_REVIEW = True

PANEL_VERSION = "team01-panel/2-live-solver"


def _utcnow() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def _cmd(payload=None) -> Command:
    return Command(request_id="team01-solver-%s" % uuid.uuid4().hex,
                   payload=payload or {})


def infer_text(dsn: str, gateway, *, allocation_id: str, op_id: str,
               prompt: str,
               max_output_tokens: int = MAX_OUTPUT_TOKENS) -> dict:
    """One broker-routed model call. Never raises for model-side failure."""
    ensured = broker.ensure_operation(
        dsn, operation_id=op_id, effect=broker.MODEL_INFERENCE,
        payload={"model": MODEL,
                 "messages": [{"role": "user", "content": prompt}],
                 "max_output_tokens": max_output_tokens,
                 "deadline_ms": DEADLINE_MS,
                 "reasoning_effort": EFFORT},
        allocation_id=allocation_id, retries=RETRIES)
    exposure = int((ensured.data or {}).get("exposure", 0))
    if ensured.code not in (ResultCode.APPLIED, ResultCode.ALREADY_APPLIED):
        return {"text": None, "usage": {"in": 0, "out": 0}, "stop": "",
                "exposure": exposure, "outcome": "refused-ensure",
                "error": str(ensured.detail), "receipts": []}
    broker.dispatch_operation(dsn, op_id, gateway=gateway)
    receipts = _panel_live_receipts(dsn, op_id)
    text, usage, stop = None, {"in": 0, "out": 0}, ""
    message = ""
    for receipt in receipts:
        content = dict(receipt.get("content") or {})
        if receipt.get("outcome") == "success" and "text" in content:
            text = content["text"]
            raw = dict(content.get("usage") or {})
            usage = {"in": int(raw.get("input_tokens", 0) or 0),
                     "out": int(raw.get("output_tokens", 0) or 0)}
            stop = str(content.get("stop_reason", ""))
            break
        if receipt.get("outcome") == "unknown" and content.get("error"):
            message = str(content["error"])
    if text is None:
        return {"text": None, "usage": usage, "stop": stop,
                "exposure": exposure,
                "outcome": "fallback-%s" % _panel_live_classify(message),
                "error": "gateway gave no text: %s" % message,
                "receipts": [r["receipt_identity"] for r in receipts]}
    return {"text": text, "usage": usage, "stop": stop,
            "exposure": exposure, "outcome": "model-text",
            "error": "",
            "receipts": [r["receipt_identity"] for r in receipts]}


def _panel_live_receipts(dsn: str, operation_id: str) -> list:
    from settlement import db
    from psycopg.rows import dict_row

    with db.connect(dsn) as conn:
        with conn.cursor(row_factory=dict_row) as cur:
            cur.execute("SELECT receipt_identity, outcome, content FROM receipts"
                        " WHERE operation_id = %s ORDER BY receipt_identity",
                        (operation_id,))
            rows = [dict(row) for row in cur.fetchall()]
            conn.commit()
            return rows


def _panel_live_classify(message: str) -> str:
    text = (message or "").lower()
    if "timeout" in text or "timed out" in text:
        return "timeout"
    if not text or "no text" in text or "empty" in text:
        return "empty-output"
    if "auth" in text or "rate" in text or "limit" in text:
        return "gateway-error"
    return "gateway-error"


ENVELOPE_INSTRUCTION = (
    "Reply with exactly one JSON object and nothing else, shaped "
    '{"files": { "<owned relpath>": "<complete file content>" }, '
    '"notes": "<one or two sentences about the repair>"}. '
    "Include an entry for every owned path, even if unchanged. "
    "Do not add, rename or omit paths. Full file contents, not diffs.")


def parse_ctor_envelope(text: str | None, owned: list) -> dict:
    """Strict constructor-output parse. Anything unusable yields no files."""
    if not text or not text.strip():
        return {"files": None, "notes": "", "error": "empty-output"}
    body = text.strip()
    if body.startswith("```"):
        lines = body.split("\n")
        lines = lines[1:]
        if lines and lines[-1].strip().startswith("```"):
            lines = lines[:-1]
        body = "\n".join(lines)
    try:
        data = json.loads(body)
    except ValueError as exc:
        return {"files": None, "notes": "",
                "error": "not-json: %s" % str(exc)[:120]}
    if not isinstance(data, dict) or not isinstance(data.get("files"), dict):
        return {"files": None, "notes": "",
                "error": "bad-shape: need {files: {path: content}}"}
    files = data["files"]
    if set(files) != set(owned):
        return {"files": None, "notes": "",
                "error": "path-mismatch: got %s want %s" % (
                    sorted(files), sorted(owned))}
    for path, content in files.items():
        if not isinstance(content, str) or not content.strip():
            return {"files": None, "notes": "",
                    "error": "empty-file: %s" % path}
    return {"files": dict(files), "notes": str(data.get("notes", "")),
            "error": ""}


def _task_brief(task_id: str, owned: list, current: dict) -> str:
    tdir = oracle.TASKS / task_id
    spec_md = (tdir / "spec.md").read_text()
    spec_json = (tdir / "spec.json").read_text()
    parts = ["TASK %s" % task_id,
             "SPECIFICATION:", spec_md.strip(),
             "SPEC PARAMS: %s" % spec_json.strip(),
             "OWNED PATHS (repair exactly these files): %s"
             % ", ".join(owned)]
    for path in owned:
        parts.append("--- %s ---\n%s" % (path, current.get(path, "")))
    return "\n".join(parts)


def _cases_text(task_id: str) -> str:
    cases = oracle.public_cases(task_id)
    lines = ["VISIBLE CHECKS (%d; hidden checks differ, do not overfit):"
             % len(cases)]
    for pos, case in enumerate(cases):
        lines.append("check %d: input=%s expected=%s"
                     % (pos, json.dumps(case["input"]),
                        json.dumps(case["expected"])))
    return "\n".join(lines)


def ctor_prompt(task_id: str, owned: list, current: dict, context: str,
                feedback: str, calls_left: int, tools_left: int) -> str:
    return "\n".join([
        _task_brief(task_id, owned, current),
        _cases_text(task_id),
        "SITUATION: %s" % context,
        "TOOL FEEDBACK FROM VISIBLE CHECKS: %s" % (feedback or "none yet"),
        "BUDGET: %d model calls and %d tool runs left including this one."
        % (calls_left, tools_left),
        "Repair the owned files so the program meets the specification on "
        "the visible checks and, above all, on unseen cases for the same "
        "specification. Keep every public entry point and call signature "
        "used by the rest of the program exactly as-is.",
        ENVELOPE_INSTRUCTION])


def review_prompt(task_id: str, owned: list, current: dict) -> str:
    return "\n".join([
        _task_brief(task_id, owned, current),
        _cases_text(task_id),
        "SITUATION: you previously repaired these files and they pass the "
        "visible checks. Review your own repair against the specification "
        "for edge cases the visible checks may miss (empty inputs, boundary "
        "values, operations the spec params name but no visible check "
        "exercises).",
        'Reply with exactly one JSON object {"verdict": "keep" | "revise", '
        '"notes": "<what you checked>"}. Nothing else.'])


def _materialize_tree(tree_files: dict, dest: Path) -> Path:
    for relpath, body in tree_files.items():
        target = dest / relpath
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(body)
    return dest


def run_public_tool(dsn: str, *, launchers: dict, runs_root: Path,
                    op_tag: str, tree_files: dict, task_id: str,
                    allocation_id: str) -> dict:
    """Costed visible-check run through a broker sandbox operation."""
    area = runs_root / ("tool-%s" % op_tag)
    _materialize_tree(tree_files, area / "tree")
    cases_path = area / "cases.json"
    cases_path.write_text(json.dumps(oracle.public_cases(task_id)))
    op_id = "tool-%s" % op_tag
    ensured = broker.ensure_operation(
        dsn, operation_id=op_id, effect=broker.SANDBOX_EXEC,
        payload={"profile": "local-process",
                 "argv": [sys.executable, str(ROOT / "pubcheck.py"),
                          str(area / "tree"), str(cases_path)],
                 "timeout_ms": 60_000},
        allocation_id=allocation_id, retries=0)
    if ensured.code not in (ResultCode.APPLIED, ResultCode.ALREADY_APPLIED):
        return {"passed": 0, "failed": 0, "total": 0, "failures": [],
                "error": "tool-ensure-refused: %s" % ensured.detail,
                "op_id": op_id, "receipts": []}
    broker.dispatch_operation(dsn, op_id, launchers=launchers)
    receipts = _panel_live_receipts(dsn, op_id)
    summary = {"passed": 0, "failed": 0, "total": 0, "failures": [],
               "error": "no-tool-receipt"}
    for receipt in receipts:
        content = dict(receipt.get("content") or {})
        worker = dict(((content.get("data") or {}).get("worker") or {}))
        data = dict(worker.get("data") or {})
        if worker.get("status") == "ok" and "passed" in data:
            summary = {"passed": int(data["passed"]),
                       "failed": int(data.get("failed", 0)),
                       "total": int(data.get("total", 0)),
                       "failures": list(data.get("failures", [])),
                       "error": ""}
            break
        if worker.get("status") == "error":
            summary = {"passed": 0, "failed": 0, "total": 0,
                       "failures": [],
                       "error": "tool-error: %s" % worker.get("error", "")}
            break
    summary["op_id"] = op_id
    summary["receipts"] = [r["receipt_identity"] for r in receipts]
    return summary


def _summarize_tool(summary: dict) -> str:
    if summary.get("error"):
        return "tool error: %s" % summary["error"]
    bits = ["%d/%d visible checks pass" % (summary["passed"],
                                           summary["total"])]
    for fail in summary.get("failures", [])[:3]:
        bits.append("miss input=%s expected=%s got=%s"
                    % (json.dumps(fail.get("input")),
                       json.dumps(fail.get("expected")),
                       json.dumps(fail.get("got"))))
    return "; ".join(bits)


def _live_children(shape: str, snapshot: dict) -> list:
    """Child specs with model-owned src paths only (spec.json stays fixed)."""
    owned = sorted(p for p in snapshot if p.startswith("src/"))
    bindings = {"base_%d" % pos: path
                for pos, path in enumerate(sorted(snapshot))}
    if shape == "single":
        return [{"node_id": "w1",
                 "obligation": "repair the whole task tree",
                 "owned_paths": owned,
                 "output_contract": {"entry": "whole-tree",
                                     "checks": ["public"]},
                 "input_bindings": dict(bindings)}]
    if shape == "alternatives":
        whole = sorted(snapshot)
        return [{"node_id": node,
                 "obligation": "independent whole-task attempt",
                 "owned_paths": whole,
                 "output_contract": {"entry": "whole-tree",
                                     "checks": ["public"]},
                 "input_bindings": dict(bindings)}
                for node in ("w1", "w2")]
    mods = [p for p in owned if p != "src/app.py"]
    first = mods[0] if mods else owned[0]
    second = mods[1] if len(mods) > 1 else owned[-1]
    return [{"node_id": "w1", "obligation": "repair %s" % first,
             "owned_paths": [first],
             "output_contract": {"entry": first, "checks": ["public"]},
             "input_bindings": {"base": first}},
            {"node_id": "w2", "obligation": "repair %s" % second,
             "owned_paths": [second],
             "output_contract": {"entry": second, "checks": ["public"]},
             "input_bindings": {"base": second}}]


class SolverCtx:
    def __init__(self, dsn: str, gateway, launchers: dict, runs_root: Path,
                 allocation_id: str, tag: str, task_id: str,
                 snapshot: dict, area: Path) -> None:
        self.dsn = dsn
        self.gateway = gateway
        self.launchers = launchers
        self.runs_root = runs_root
        self.allocation_id = allocation_id
        self.tag = tag
        self.task_id = task_id
        self.snapshot = snapshot
        self.area = area
        self.nonce = tag.rsplit("-", 1)[-1]
        self.trace: list = []
        self.model_calls = 0
        self.tool_calls = 0

    def _record_call(self, entry: dict) -> None:
        self.trace.append(entry)
        base = self.area / entry["op_id"]
        (base.with_suffix(".prompt.txt")).write_text(
            entry.get("prompt", ""))
        (base.with_suffix(".response.txt")).write_text(
            entry.get("text") or "")
        (base.with_suffix(".parsed.json")).write_text(json.dumps(
            {k: v for k, v in entry.items()
             if k not in ("prompt", "text")}, indent=2))

    def ctor_round(self, *, node: str, owned: list, current: dict,
                   context: str, feedback: str, calls_left: int,
                   tools_left: int, prefix: str) -> dict:
        op_id = "%s-ctor-%s-%s-%d" % (prefix, node, self.tag,
                                      len(self.trace))
        prompt = ctor_prompt(self.task_id, owned, current, context,
                             feedback, calls_left, tools_left)
        result = infer_text(self.dsn, self.gateway,
                            allocation_id=self.allocation_id, op_id=op_id,
                            prompt=prompt)
        self.model_calls += 1
        parsed = parse_ctor_envelope(result["text"], owned)
        entry = {"kind": "ctor", "node": node, "op_id": op_id,
                 "prompt": prompt, "text": result["text"],
                 "usage": result["usage"], "stop": result["stop"],
                 "outcome": result["outcome"], "error": result["error"],
                 "parse_error": parsed["error"],
                 "notes": parsed["notes"],
                 "files_digest": (team.output_digest(parsed["files"])
                                  if parsed["files"] else None),
                 "receipts": result["receipts"]}
        self._record_call(entry)
        return {"files": parsed["files"], "error": parsed["error"],
                "notes": parsed["notes"], "op_id": op_id}

    def tool_round(self, *, tree_files: dict, prefix: str) -> dict:
        op_tag = "%s-%s-%d" % (prefix, self.tag, len(self.trace))
        summary = run_public_tool(
            self.dsn, launchers=self.launchers, runs_root=self.runs_root,
            op_tag=op_tag, tree_files=tree_files, task_id=self.task_id,
            allocation_id=self.allocation_id)
        self.tool_calls += 1
        self.trace.append({"kind": "tool", "op_id": summary["op_id"],
                           "summary": {k: v for k, v in summary.items()
                                       if k != "receipts"},
                           "receipts": summary["receipts"]})
        return summary

    def _full_tree(self, node_files: dict) -> dict:
        tree = dict(self.snapshot)
        for files in node_files.values():
            if files:
                tree.update(files)
        return tree


def solve_S(ctx: SolverCtx, *, owned: list, prefix: str) -> dict:
    """Iterative whole-task repair with tool feedback and self-review."""
    current = {p: ctx.snapshot[p] for p in owned}
    feedback, best, best_pass = "", None, -1
    for round_no in range(MAX_CTOR_ROUNDS_S):
        calls_left = MAX_CTOR_ROUNDS_S - round_no + (1 if SELF_REVIEW else 0)
        tools_left = MAX_TOOL_CALLS_S - ctx.tool_calls
        out = ctx.ctor_round(
            node="w1", owned=owned, current=current,
            context="solo repair attempt %d" % (round_no + 1),
            feedback=feedback, calls_left=calls_left,
            tools_left=tools_left, prefix=prefix)
        if out["files"] is None:
            feedback = "your reply was unusable: %s" % out["error"]
            continue
        current = dict(out["files"])
        summary = ctx.tool_round(tree_files=ctx._full_tree({"w1": current}),
                                 prefix=prefix)
        if summary.get("error") or summary["failed"]:
            feedback = _summarize_tool(summary)
            if summary["passed"] > best_pass:
                best, best_pass = dict(current), summary["passed"]
            continue
        if not SELF_REVIEW:
            return {"w1": dict(current), "rounds": round_no + 1,
                    "reviewed": False}
        rev_op = "%s-review-%s-%d" % (prefix, ctx.tag, len(ctx.trace))
        rev = infer_text(ctx.dsn, ctx.gateway,
                         allocation_id=ctx.allocation_id, op_id=rev_op,
                         prompt=review_prompt(ctx.task_id, owned, current))
        ctx.model_calls += 1
        verdict = parse_review_envelope(rev["text"])
        ctx.trace.append({"kind": "review", "op_id": rev_op,
                          "usage": rev["usage"], "outcome": rev["outcome"],
                          "error": rev["error"], "verdict": verdict,
                          "receipts": rev["receipts"]})
        base = ctx.area / rev_op
        (base.with_suffix(".prompt.txt")).write_text(
            review_prompt(ctx.task_id, owned, current))
        (base.with_suffix(".response.txt")).write_text(rev["text"] or "")
        if verdict == "keep" or round_no + 1 >= MAX_CTOR_ROUNDS_S:
            return {"w1": dict(current), "rounds": round_no + 1,
                    "reviewed": True, "review": verdict}
        feedback = "your own review asked for revision"
    return {"w1": best, "rounds": MAX_CTOR_ROUNDS_S, "reviewed": False}


def parse_review_envelope(text: str | None) -> str:
    """Return keep|revise|unknown from a self-review reply."""
    if not text or not text.strip():
        return "unknown"
    body = text.strip()
    if body.startswith("```"):
        lines = body.split("\n")[1:]
        if lines and lines[-1].strip().startswith("```"):
            lines = lines[:-1]
        body = "\n".join(lines)
    try:
        data = json.loads(body)
    except ValueError:
        return "unknown"
    verdict = str((data or {}).get("verdict", "")).strip().lower()
    return verdict if verdict in ("keep", "revise") else "unknown"


def _final_tree_live(snapshot: dict, shape: str, submitted: dict,
                     candidate_digest: str) -> tuple:
    """Assemble the scored tree from submitted constructor bytes only.

    submitted maps node_id -> files|None. Returns (tree, note). Anything
    missing falls back to the broken snapshot for that node and is noted;
    a fully refused episode must not be scored as success by the caller.
    """
    if shape == "alternatives":
        for node, files in submitted.items():
            if files and team.output_digest(files) == candidate_digest:
                tree = dict(snapshot)
                tree.update(files)
                return tree, "selected-%s" % node
        return dict(snapshot), "no-candidate-match"
    tree = dict(snapshot)
    missing = [node for node, files in submitted.items() if not files]
    for files in submitted.values():
        if files:
            tree.update(files)
    return tree, ("missing-%s" % ",".join(sorted(missing)) if missing
                  else "assembled")


def _remap_shape(node_bytes: dict, from_shape: str, to_shape: str,
                 snapshot: dict) -> dict:
    """Remap constructor bytes across shapes for a labeled probe override."""
    if from_shape == "single" and to_shape == "decompose":
        whole = node_bytes.get("w1")
        if not whole:
            return {"w1": None, "w2": None}
        kids = _live_children("decompose", snapshot)
        return {c["node_id"]: {p: whole[p] for p in c["owned_paths"]
                               if p in whole}
                if whole else None for c in kids}
    if from_shape == "decompose" and to_shape == "single":
        merged: dict = {}
        for files in node_bytes.values():
            if files:
                merged.update(files)
        return {"w1": merged or None}
    return dict(node_bytes)


def run_live_repair_episode(dsn: str, *, gateway, launchers: dict,
                            runs_root: Path, evidence_root: Path | None,
                            tag: str, task_id: str,
                            arm: str, repeat: int = 1,
                            probe: str | None = None,
                            substitute: dict | None = None,
                            disconnect: list | None = None,
                            authored_nodes: dict | None = None,
                            repair_rounds: int = 1,
                            shape_override: str | None = None,
                            panel: str = "dev",
                            directive: str | None = None) -> dict:
    """One S/P/T episode whose repairs are model-generated bytes.

    substitute maps node_id -> files: the constructor bytes for that node
    are replaced (valid-but-wrong control) with digests recorded.
    disconnect lists node_ids whose constructor output is dropped: the
    submit path then refuses for lack of an artifact.
    authored_nodes maps node_id -> {files, label}: labeled diagnostic
    controls (e.g. an incompatible interface) submitted as-is.
    panel names the comparison panel (dev/eval/transfer) for evidence
    grouping. directive carries frozen coordination text for the warm-T
    arm; warm-T without a directive is refused.
    """
    started = time.monotonic()
    epid = "live2-%s-%s-r%d" % (arm, task_id, repeat)
    if probe:
        epid = "%s-%s" % (epid, probe)
    # Nonce keeps constructor/tool op ids unique across reruns on one DB;
    # without it a rerun would silently reuse stale receipts and responses.
    nonce = uuid.uuid4().hex[:8]
    area = runs_root / epid
    area.mkdir(parents=True, exist_ok=True)
    _panel.register.ensure_foundation(dsn)
    seed = _panel._seed(dsn, "%s-%s" % (tag, epid))
    snapshot = _panel._snapshot(task_id)
    ctx = SolverCtx(dsn, gateway, launchers, runs_root, seed["allocation_id"],
                    "%s-%s-%s" % (tag, epid, nonce), task_id, snapshot,
                    area)
    prefix = "%s-%s-%s" % (tag, epid, nonce)
    solver_notes: dict = {}
    controls = {"substituted": {}, "disconnected": sorted(disconnect or []),
                "authored": {}}
    if arm == "S":
        owned = sorted(p for p in snapshot if p.startswith("src/"))
        solved = solve_S(ctx, owned=owned, prefix=prefix)
        shape, node_bytes = "single", {"w1": solved["w1"]}
        solver_notes = {"rounds": solved["rounds"],
                        "reviewed": solved["reviewed"]}
    elif arm == "P":
        owned = sorted(snapshot)
        node_bytes = solve_P(ctx, owned=owned, prefix=prefix)
        shape = "alternatives"
    elif arm in ("T", "cold-T", "warm-T"):
        if arm == "warm-T" and not directive:
            return _refused_record(ctx, epid, arm, task_id, repeat, probe,
                                   "unshaped", controls,
                                   "warm-T without a frozen directive",
                                   started, evidence_root, panel=panel)
        solved = solve_T(ctx, prefix=prefix,
                         directive=directive if arm == "warm-T" else None)
        shape, node_bytes = solved["shape"], dict(solved["nodes"])
        solver_notes = {"rationale": solved["rationale"],
                        "plan_source": solved["plan_source"]}
        if directive and arm == "warm-T":
            solver_notes["directive_digest"] = hashlib.sha256(
                directive.encode()).hexdigest()
        if shape_override in ("single", "decompose") \
                and shape_override != shape:
            node_bytes = _remap_shape(node_bytes, shape, shape_override,
                                      snapshot)
            solver_notes["shape_override"] = shape_override
            solver_notes["model_shape"] = shape
            shape = shape_override
        ctx.trace.append({"kind": "children", "shape": shape,
                          "spec": _live_children(shape, snapshot)})
    else:
        raise SettlementError("unknown live-solver arm %r" % arm)
    for node, files in (authored_nodes or {}).items():
        node_bytes[node] = dict(files["files"])
        controls["authored"][node] = files["label"]
    for node, files in (substitute or {}).items():
        if node in node_bytes and node_bytes[node]:
            controls["substituted"][node] = {
                "constructor_digest": team.output_digest(node_bytes[node]),
                "substitute_digest": team.output_digest(files)}
            node_bytes[node] = dict(files)
    for node in disconnect or []:
        node_bytes[node] = None
    children = [c for c in _live_children(shape, snapshot)
                if c["node_id"] in node_bytes]
    proposed = team.propose_team_plan(
        dsn, _cmd(), parent_obligation="%s:repair %s" % (
            seed["investigation_id"], task_id),
        snapshot_digest=team.register_snapshot(
            dsn, _cmd(), dict(snapshot)).data["snapshot_digest"],
        shape=shape, children=children,
        interface_contract={"shapes": [shape], "new_paths": []},
        join_rules=_panel._join_rules(shape, task_id),
        allocation_id=seed["allocation_id"],
        policy_response={"arm": arm, "shape": shape,
                         "solver": solver_notes,
                         "constructor_ops": [
                             t["op_id"] for t in ctx.trace
                             if t.get("kind") in ("ctor", "plan")]})
    if proposed.code != ResultCode.APPLIED:
        return _refused_record(ctx, epid, arm, task_id, repeat, probe,
                               shape, controls, "plan refused: %s"
                               % proposed.detail, started, evidence_root,
                               panel=panel)
    plan_id = proposed.data["plan_id"]
    receipts = _panel._dispatch(dsn, plan_id, launchers)
    revision = 1
    submitted_digests = _submit_nodes(dsn, plan_id, revision, node_bytes,
                                      receipts)
    if any(v is None for v in submitted_digests.values()):
        return _refused_record(ctx, epid, arm, task_id, repeat, probe,
                               shape, controls, "no constructor artifact "
                               "for %s: submission refused" % ",".join(
                                   sorted(n for n, v in
                                          submitted_digests.items()
                                          if v is None)),
                               started, evidence_root, plan_id=plan_id,
                               panel=panel)
    joined, join = _join(dsn, plan_id, launchers, revision)
    join_attempts = [{"revision": revision,
                      "passed": bool(join.get("passed")),
                      "check_operation": join.get("check_operation", ""),
                      "assemble_code": join.get("assemble_code", ""),
                      "assemble_detail": join.get("assemble_detail", "")}]
    repairs = 0
    while (joined.code != ResultCode.APPLIED and repairs < repair_rounds
           and _join_failed_check(join)):
        repaired = _repair_round(ctx, plan_id, revision, node_bytes,
                                 children, join, receipts, prefix)
        if repaired is None:
            break
        repairs += 1
        revision += 1
        submitted_digests = repaired["digests"]
        joined, join = _join(dsn, plan_id, launchers, revision)
        join_attempts.append(
            {"revision": revision, "passed": bool(join.get("passed")),
             "check_operation": join.get("check_operation", ""),
             "assemble_code": join.get("assemble_code", ""),
             "assemble_detail": join.get("assemble_detail", "")})
    template_digest = solver_notes.get("directive_digest")
    record = _finish(dsn, ctx, epid, arm, task_id, repeat, probe, shape,
                     plan_id, revision, node_bytes, submitted_digests,
                     joined, join, controls, repairs, started,
                     solver_notes, join_attempts, panel, template_digest)
    if evidence_root is not None:
        dest = Path(evidence_root) / "episodes"
        dest.mkdir(parents=True, exist_ok=True)
        (dest / ("%s.json" % epid)).write_text(json.dumps(record, indent=2))
    return record


def _submit_nodes(dsn: str, plan_id: str, revision: int, node_bytes: dict,
                  receipts: dict) -> dict:
    digests = {}
    for node, files in node_bytes.items():
        if not files:
            digests[node] = None
            continue
        reg = team.register_output(dsn, _cmd(), dict(files))
        if reg.code != ResultCode.APPLIED:
            raise SettlementError("output refused: %s" % reg.detail)
        attempt = team.child_attempt(dsn, plan_id, node)
        result = team.submit_child(
            dsn, _cmd({"plan_id": plan_id}), plan_revision=revision,
            node_id=node,
            input_digests=team.expected_inputs(dsn, plan_id, node),
            ownership_generation=attempt["ownership_generation"],
            output_digest=reg.data["output_digest"],
            receipt_refs=receipts[node])
        if result.code != ResultCode.APPLIED:
            raise SettlementError("submit refused: %s" % result.detail)
        digests[node] = reg.data["output_digest"]
    return digests


def _join(dsn: str, plan_id: str, launchers: dict, revision: int) -> tuple:
    joined = team.assemble_and_join(dsn, _cmd(), plan_id=plan_id,
                                    launchers=launchers)
    if joined.data.get("candidate_digest"):
        join = dict(team.join_record(dsn, plan_id, revision))
    else:
        join = {"passed": False, "candidate_digest": "",
                "join_receipt": "",
                "check_operation": joined.data.get("check_operation", "")}
    join["assemble_code"] = str(joined.code)
    join["assemble_detail"] = str(joined.detail or "")
    return joined, join


def _join_failed_check(join: dict) -> bool:
    """True only when the integration check ran and rejected the join."""
    return not join.get("passed") and bool(join.get("check_operation"))


def _repair_round(ctx: SolverCtx, plan_id: str, revision: int,
                  node_bytes: dict, children: list, join: dict,
                  receipts: dict, prefix: str) -> dict | None:
    owned_of = {c["node_id"]: c["owned_paths"] for c in children}
    detail = join.get("assemble_detail", "")[:1500]
    changed = False
    for node, files in list(node_bytes.items()):
        if not files:
            continue
        current = dict(files)
        out = ctx.ctor_round(
            node=node, owned=owned_of[node], current=current,
            context="bounded repair: the assembled candidate failed the "
                    "integration check",
            feedback="integration check: %s" % (detail or "no detail"),
            calls_left=1, tools_left=1, prefix=prefix)
        if out["files"] is None:
            continue
        node_bytes[node] = dict(out["files"])
        changed = True
    if not changed:
        return None
    revised = team.revise_team_plan(
        dsn=ctx.dsn, cmd=_cmd(), plan_id=plan_id,
        children=children, reason="bounded repair round after check "
        "failure",
        rework=[node for node, files in node_bytes.items() if files])
    if revised.code != ResultCode.APPLIED:
        return None
    # Revision 2 mints fresh child operations: dispatch them and submit
    # against the new receipts; revision-1 receipts are not reusable.
    fresh = _panel._dispatch(ctx.dsn, plan_id, ctx.launchers)
    digests = _submit_nodes(ctx.dsn, plan_id, revision + 1, node_bytes,
                            fresh)
    return {"revised": True, "digests": digests}


def _finish(dsn: str, ctx: SolverCtx, epid: str, arm: str, task_id: str,
            repeat: int, probe: str | None, shape: str, plan_id: str,
            revision: int, node_bytes: dict, submitted_digests: dict,
            joined, join: dict, controls: dict, repairs: int,
            started: float, solver_notes: dict,
            join_attempts: list, panel: str,
            template_digest: str | None = None) -> dict:
    frozen_digest = None
    if joined.code == ResultCode.APPLIED:
        frozen = team.freeze_candidate(
            dsn, _cmd(), plan_id=plan_id,
            candidate_digest=joined.data["candidate_digest"])
        if frozen.code == ResultCode.APPLIED:
            frozen_digest = frozen.data["frozen_candidate"]
    final, assembly_note = _final_tree_live(
        ctx.snapshot, shape, node_bytes, joined.data.get("candidate_digest",
                                                         ""))
    with tempfile.TemporaryDirectory(prefix="team01-live2-eval-") as tmp:
        src = _materialize_tree(final, Path(tmp) / "tree")
        public = oracle.evaluate_tree(src / "src",
                                      oracle.public_cases(task_id))
        protected = oracle.evaluate_tree(src / "src",
                                        oracle.protected_cases(task_id))
    solved = bool(frozen_digest) and protected["failed"] == 0
    ctor_ops = [t for t in ctx.trace if t.get("kind") in ("ctor", "plan",
                                                          "review")]
    usage_in = sum(t["usage"]["in"] for t in ctor_ops)
    usage_out = sum(t["usage"]["out"] for t in ctor_ops)
    receipts = sorted({r for t in ctx.trace for r in t.get("receipts", [])}
                      | ({join.get("join_receipt", "")} - {""}))
    return {"episode_id": epid, "panel": panel, "arm": arm,
            "task_id": task_id, "repeat": repeat, "probe": probe,
            "panel_version": PANEL_VERSION, "plan_id": plan_id,
            "revision": revision, "shape": shape,
            "template_digest": template_digest,
            "snapshot_digest": team.snapshot_digest(ctx.snapshot),
            "outcome": "success" if solved else "failure",
            "public": public, "protected": protected,
            "join": {"passed": bool(join.get("passed")),
                     "join_receipt": join.get("join_receipt", ""),
                     "check_operation": join.get("check_operation", ""),
                     "candidate_digest": join.get("candidate_digest", ""),
                     "assemble_code": join.get("assemble_code", ""),
                     "assemble_detail": join.get("assemble_detail", ""),
                     "assembly_note": assembly_note},
            "frozen_digest": frozen_digest,
            "submitted_digests": submitted_digests, "nonce": ctx.nonce,
            "allocation_id": ctx.allocation_id,
            "manifest_sha256": _panel._manifest_sha(),
            "receipts": receipts,
            "solver": solver_notes, "join_attempts": join_attempts,
            "controls": controls, "repairs": repairs,
            "constructor_ops": ctor_ops,
            "tool_ops": [t for t in ctx.trace if t.get("kind") == "tool"],
            "model_calls": ctx.model_calls, "tool_calls": ctx.tool_calls,
            "usage": {"in": usage_in, "out": usage_out},
            "costs": {"model_invocations": ctx.model_calls,
                      "model_tokens": {"in": usage_in, "out": usage_out},
                      "tool_executions": ctx.tool_calls},
            "simulated": False,
            "live_source": "model-repair",
            "wall_s": round(time.monotonic() - started, 3)}


