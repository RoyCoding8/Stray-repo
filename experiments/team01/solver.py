"""Live solver loop for Team 01 repair arms (CB2-01 completion).

Every arm repairs with actual model-generated bytes through broker-routed
operations. No reference trees are loaded anywhere in this module: child
submissions carry constructor-returned file bytes, and the scored tree is
materialized from those submissions only.

Prompt hygiene: the model sees the task id, spec text, owned source files,
the public (visible) cases and costed tool observations. It never sees the
task family, defect counts, valid/invalid kind labels or protected cases.

Arms (same model, configuration, task/source/tool access, root authority):
- S: single node, iterative planning/edits/self-review within a call budget.
- P: two independent whole-task attempts, no shared history; the join
  check selects on public cases.
- T: one plan call chooses single vs decompose from the visible brief;
  per-node constructor calls repair owned paths with the plan as context.

A constructor call that returns empty/unparseable/out-of-scope bytes yields
no bytes; the loop spends its bounded budget and then records no-candidate
for that node. Nothing falls back to reference material.
"""
