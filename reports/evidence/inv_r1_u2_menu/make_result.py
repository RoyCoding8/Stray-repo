MODEL = "openrouter/nvidia/nemotron-3-ultra-550b-a55b:free"
ENV_FILE = Path.home() / ".config/agent-society-live.env"
FORBIDDEN_STORE = "ec02test_live"
STUDY_ROOT = "inv-r1-u2-menu"
TASK_ID = "ad01-w2-within-sw-00"
MAX_QUERIES = 8

# Reservation units, not sends. The cap sheet's own allowance, so the study's
# authority is derived from the frozen request bounds rather than typed in.
def _study_units() -> int:
    from experiments.ad01 import s09_cap_sheet
    return int(s09_cap_sheet.load().unit_allowance.units)

# What the model is asked to write. Two calls, because the claim under test is
# about the menu's shapes: a member written to the primitive the contract newly
# offers, and a member that trusts the contract's claim that `method` has no
# default and omits it. Both run through the real child, the real oracle
# channel and the real launcher.
PRIMITIVE_MEMBER = (
    "def ENTRY(task, oracle, max_queries=16):\n"
    "    build, order = software_atoms(task)\n"
    "    count = len(task['ops'])\n"
    "    p = lambda c: oracle.query(c)\n"
    "    out = ddmin_reduce(count, build, p, max_queries=max_queries)\n"
    "    return {'candidate': build(out['kept']),\n"
    "            'queries': out['queries']}\n"
)
OMITTED_METHOD_MEMBER = (
    "def ENTRY(task, oracle, max_queries=16):\n"
    "    out = reduce_software(task, oracle, max_queries=max_queries)\n"
    "    return {'candidate': out['candidate'],\n"
    "            'queries': out['queries']}\n"
)


def _load_env() -> dict:
    """Read the credential file into a dict. The secret is never returned."""
    env: dict = {}
    for line in ENV_FILE.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        env[key.strip()] = value.strip().strip("'\"")
    return env


def _params(fn: ast.FunctionDef) -> tuple:
    positional = [a.arg for a in fn.args.posonlyargs] + [a.arg for a in fn.args.args]
    keyword = [a.arg for a in fn.args.kwonlyargs]
    return positional, keyword


def _real_signature(fn) -> dict:
    import inspect
    sig = inspect.signature(fn)
    return {
        "positional": [p.name for p in sig.parameters.values()
                       if p.kind in (p.POSITIONAL_ONLY, p.POSITIONAL_OR_KEYWORD)],
        "keyword_only": [p.name for p in sig.parameters.values()
                         if p.kind is p.KEYWORD_ONLY],
        "defaults": {p.name: repr(p.default) for p in sig.parameters.values()
                     if p.default is not p.empty},
    }


def menu_audit() -> dict:
    """Compare the declared menu against the wrapper the child process runs.

    `child_contract()` is what the constructor prompt is built from.
    `_child_wrapper_source()` is spliced into the driver that executes. They
    are two artefacts, the shipped tests read only the first, and the wrapper
    is generated by a uniform template that assumes every binding takes
    `(task, oracle, method, max_queries)`. Only two of the six do.
    """
    from experiments.ad01 import method_exec
    from experiments.representation import reducers

    contract = method_exec.child_contract()["callables"]
    wrapper_src = method_exec._child_wrapper_source()
    wrappers = {n.name: n for n in ast.parse(wrapper_src).body
                if isinstance(n, ast.FunctionDef)}

    findings = []
    for name, spec in sorted(contract.items()):
        binding = spec.get("binding")
        wrapper = wrappers.get(name)
        entry = {
            "callable": name,
            "binding": binding,
            "declared_signature": str(spec.get("signature", "")),
            "wrapper_present": wrapper is not None,
        }
        problems = []
        if wrapper is None:
            problems.append("declared-but-not-wrapped")
        else:
            positional, keyword = _params(wrapper)
            entry["wrapper_positional"] = positional
            entry["wrapper_keyword_only"] = keyword
            defaults = {}
            for node in list(wrapper.args.defaults) + [
                    d for d in wrapper.args.kw_defaults if d is not None]:
                if isinstance(node, ast.Constant):
                    defaults[ast.unparse(node)] = True
            for node, name in zip(wrapper.args.kw_defaults, keyword):
                if node is not None and isinstance(node, ast.Constant):
                    defaults[name] = ast.literal_eval(node)
            entry["wrapper_defaults"] = defaults
            if defaults.get("method") == "ddmin":
                problems.append(
                    "wrapper-defaults-method-to-ddmin-which-is-the-authored-answer")
            if "no default" in entry["declared_signature"] \
                    and "method" in defaults:
                problems.append("contract-promises-no-default-wrapper-has-one")
        if binding:
            target = getattr(reducers, binding.split(".")[-1], None)
            if target is not None:
                real = _real_signature(target)
                entry["bound_target"] = real
                if wrapper is not None:
                    wp, wk = _params(wrapper)
                    if (len(wp) != len(real["positional"])
                            or wp != real["positional"]):
                        problems.append("wrapper-arity-and-names-do-not-fit-binding")
        entry["problems"] = problems
        findings.append(entry)

    return {
        "contract_version": method_exec.child_contract()["version"],
        "wrapper_source": wrapper_src,
        "wrapper_digest": hashlib.sha256(wrapper_src.encode()).hexdigest(),
        "callables": findings,
        "problem_count": sum(len(f["problems"]) for f in findings),
    }


def _run_member(source: str, capability_id: str) -> dict:
    from experiments.ad01 import method_exec, worlds
    task = worlds.load_task(worlds.FROZEN_DIR, TASK_ID)
    member = {"capability_id": capability_id, "entry": "ENTRY",
              "method_source": source}
    try:
        result = method_exec.run_member_out_of_process(
            member, task, max_queries=MAX_QUERIES, timeout_ms=20_000)
    except Exception as exc:
        return {"status": "error", "error": type(exc).__name__ + ": "
                + str(exc)[:400]}
    return {"status": "ok", "operation_id": result.get("operation_id"),
            "queries": result.get("queries"),
            "executed_source_digest": result.get("source_digest")}


def execution_probes() -> dict:
    """Run both menu shapes through the real child, the real oracle channel."""
    return {
        "task_id": TASK_ID,
        "max_queries": MAX_QUERIES,
        "primitive_call_against_offered_menu": _run_member(
            PRIMITIVE_MEMBER, "u2-primitive-probe"),
        "omitted_method_against_no_default_contract": _run_member(
            OMITTED_METHOD_MEMBER, "u2-default-probe"),
    }


def _census_prompt() -> str:
    from experiments.ad01 import method_exec
    return json.dumps({
        "instruction": (
            "Write the complete python source of one module-level function "
            "ENTRY(task, oracle, max_queries=16) that reduces a software "
            "fault task to a minimal candidate. Choose your reduction "
            "strategy; the contract offers more than one."),
        "entry_contract": method_exec.entry_contract(),
        "callables": method_exec.child_contract()["callables"],
    }, sort_keys=True)


def _named_method(prompt: str, response: str) -> str:
    """Which strategy the response names, if any, by the primitive it calls."""
    lowered = (response or "").lower()
    picked = [name for name in ("greedy", "ddmin")
              if name in lowered]
    if not picked:
        return "none"
    return picked[0] if len(picked) == 1 else "both"


def choice_census(dsn: str) -> dict:
    """One live construction call through the durable reservation owner.

    `authority.admit_study_call` then `broker.dispatch_operation`, the same
    path every other admitted operation takes. The E4 caveat records a prior
    run that bypassed the reservation owner; this one does not.
    """
    from settlement import authority, broker, db, gateway_http
    from settlement.config import Settings

    if FORBIDDEN_STORE in dsn:
        raise SystemExit("refusing the live store")
    db.apply_migrations(dsn, ROOT / "migrations")

    env = _load_env()
    for name in ("SETTLEMENT_GATEWAY_ENDPOINT", "SETTLEMENT_GATEWAY_KEY",
                 "SETTLEMENT_EXPECTED_ROUTE"):
        os.environ[name] = env[name]

    from experiments.ad01 import s09_run_isolation
    identity = s09_run_isolation.study_root_for(STUDY_ROOT)
    database = s09_run_isolation.create_disposable_db("u2menu")
    census_dsn = database.dsn

    settings = Settings.from_env()
    probe = gateway_http.HttpGatewayAdapter.from_settings(
        settings, expected_route=json.loads(env["SETTLEMENT_EXPECTED_ROUTE"]),
        route_mode="free")
    auth = probe.check_auth()
    if not isinstance(auth, str):
        return {"status": "gateway-unavailable",
                "error": str(auth)[:200]}

    prompt = _census_prompt()
    operation_id = "u2-census-%s" % uuid.uuid4().hex[:8]
    handle = authority.authorize_study(
        census_dsn, identity, authorized=_study_units(),
        ceilings={"max_model_calls": 2})
    granted = authority.admit_study_call(
        census_dsn, identity, kind="development", operation_id=operation_id,
        effect=broker.MODEL_INFERENCE,
        payload={"model": MODEL,
                 "messages": [{"role": "user", "content": prompt}],
                 "max_output_tokens": 2048, "deadline_ms": 240_000,
                 "reasoning_effort": "low"})
    if not hasattr(granted, "allowance"):
        return {"status": "refused",
                "reason": getattr(granted, "reason", "unknown"),
                "detail": str(getattr(granted, "detail", ""))[:300]}

    dispatch = broker.dispatch_operation(
        census_dsn, operation_id, gateway=probe)
    with db.connect(census_dsn) as conn:
        rows = conn.execute(
            "SELECT outcome, content FROM receipts"
            " WHERE operation_id = %s", (operation_id,)).fetchall()
    outcome = rows[0][0] if rows else None
    content = rows[0][1] if rows and isinstance(rows[0][1], dict) else {}
    text = str((content.get("data") or {}).get("text") or "")
    return {
        "status": "dispatched",
        "store": database.name,
        "operation_id": operation_id,
        "exposure": granted.exposure,
        "budget_kind": granted.budget_kind,
        "child_allocation_id": granted.allowance.allowance_id,
        "dispatch_state": dispatch.dispatch_state,
        "receipt_outcome": outcome,
        "prompt_digest": hashlib.sha256(prompt.encode()).hexdigest(),
        "prompt_chars": len(prompt),
        "response_chars": len(text),
        "response_digest": hashlib.sha256(text.encode()).hexdigest(),
        "method_named": _named_method(prompt, text),
    }


def route_diagnosis() -> dict:
    """One direct call to the authorized route, bypassing the study.

    This is a diagnostic and not a study operation, so it is not admitted and
    not counted against any campaign. It answers one question: is the route
    reachable, free, and returning what the frozen contract froze. Only route
    metadata and the provider's own usage block are reported. No header and no
    credential is ever read into the result.
    """
    import urllib.request

    env = _load_env()
    url = env["SETTLEMENT_GATEWAY_ENDPOINT"].rstrip("/") + "/chat/completions"
    body = json.dumps({
        "model": MODEL,
        "messages": [{"role": "user", "content": "reply with the single word OK"}],
        "max_tokens": 16,
    }).encode()
    request = urllib.request.Request(url, data=body, headers={
        "Content-Type": "application/json",
        "Authorization": "Bearer " + env["SETTLEMENT_GATEWAY_KEY"],
    })
    try:
        with urllib.request.urlopen(request, timeout=120) as response:
            payload = json.loads(response.read())
    except Exception as exc:
        return {"status": "unreachable",
                "error": type(exc).__name__ + ": " + str(exc)[:200]}

    expected = json.loads(env["SETTLEMENT_EXPECTED_ROUTE"])
    returned = {key: payload.get(key)
                for key in ("endpoint", "provider", "tier", "model")}
    return {
        "status": "responded",
        "http_status": 200,
        "returned_route": returned,
        "expected_route": expected,
        "field_mismatches": sorted(
            key for key, want in (
                ("endpoint", expected.get("endpoint")),
                ("provider", expected.get("provider")),
                ("tier", expected.get("tier")),
            )
            if not _endpoints_equal(returned.get("endpoint"), want)
            and returned.get(key) != want
        ),
        "model_matches": payload.get("model") == expected.get("resolved_model"),
        "provider_case_mismatch": (
            isinstance(returned.get("provider"), str)
            and isinstance(expected.get("provider"), str)
            and returned["provider"].lower() == expected["provider"].lower()
            and returned["provider"] != expected["provider"]),
        "provider_reported_cost": (payload.get("usage") or {}).get("cost"),
        "prompt_tokens": (payload.get("usage") or {}).get("prompt_tokens"),
        "completion_tokens": (payload.get("usage") or {}).get("completion_tokens"),
    }


def _endpoints_equal(a, b) -> bool:
    from settlement.gateway_http import _endpoints_equal as equal
    return bool(equal(a, b))


def main() -> int:
    out_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else \
        ROOT / "reports/evidence/inv_r1_u2_menu"
    out_dir.mkdir(parents=True, exist_ok=True)
    dsn = sys.argv[2] if len(sys.argv) > 2 else ""

    result = {
        "route": MODEL,
        "source_tip": os.popen("git -C %s rev-parse HEAD" % ROOT).read().strip(),
        "menu_audit": menu_audit(),
        "execution_probes": execution_probes(),
        "route_diagnosis": route_diagnosis(),
    }
    if dsn:
        result["choice_census"] = choice_census(dsn)
    (out_dir / "result.json").write_text(
        json.dumps(result, sort_keys=True, indent=1) + "\n")
    print(json.dumps({
        "problem_count": result["menu_audit"]["problem_count"],
        "primitive": result["execution_probes"][
            "primitive_call_against_offered_menu"]["status"],
        "omitted_method": result["execution_probes"][
            "omitted_method_against_no_default_contract"]["status"],
        "route": result["route_diagnosis"]["status"],
        "census": result.get("choice_census", {}).get("status", "skipped"),
    }, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
