"""Whether the M3 contrast can be informative, measured rather than asserted.

The recorded M3 gap is that the one acquired member calls the control's own
method, so the tie is a tie by construction. The fix in `77feff2` removed the
`ddmin` default from `reducers.reduce_software` and `reduce_graph`, and widened
the constructor's menu to offer `ddmin_reduce` and `greedy_reduce` separately.

That fix changed the contract, not the thing the model runs. This generator
compares the declared contract against the wrapper spliced into the child
driver, executes each menu entry through the same out-of-process path the use
phase uses, and then makes one live construction call on the authorized free
route with the prompt attested beside the response.

The three findings are of different kinds and are kept apart. The menu audit is
a deterministic property of shipped bytes and needs no gateway. The execution
probes are runtime facts about the current source. The choice census is one
observation and licenses nothing about preference.
"""

